func TestTC_MOD_01_HappyPath_Serialization(t *testing.T) {
	cfg := NewDefaultConfig()
	cfg.Profiles[0].Items = append(cfg.Profiles[0].Items, LaunchItem{
		Name:             "Terminal",
		Path:             "/usr/bin/xterm",
		Arguments:        []string{"-e", "top"},
		WorkingDirectory: "/home/user",
		DelaySeconds:     1.5,
		LaunchState:      WindowNormal,
		Enabled:          true,
	})

	if err := cfg.Validate(); err != nil {
		t.Fatalf("Validation failed on valid config: %v", err)
	}

	data, err := json.Marshal(cfg)
	if err != nil {
		t.Fatalf("JSON marshal failed: %v", err)
	}

	var restored LauncherConfig
	if err := json.Unmarshal(data, &restored); err != nil {
		t.Fatalf("JSON unmarshal failed: %v", err)
	}

	if restored.ActiveProfile != "Default" {
		t.Errorf("Expected ActiveProfile 'Default', got '%s'", restored.ActiveProfile)
	}
	if len(restored.Profiles[0].Items) != 1 {
		t.Fatalf("Expected 1 item, got %d", len(restored.Profiles[0].Items))
	}
	item := restored.Profiles[0].Items[0]
	if item.Name != "Terminal" || item.DelaySeconds != 1.5 || item.ID == "" {
		t.Errorf("Item attributes not preserved accurately: %+v", item)
	}
}

