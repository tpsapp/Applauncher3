func TestTC_MOD_03_NegativeDelayRejected(t *testing.T) {
	item := LaunchItem{
		Path:         "/usr/bin/ls",
		DelaySeconds: -2.5,
	}
	err := item.Validate()
	if !errors.Is(err, ErrNegativeDelay) {
		t.Fatalf("Expected ErrNegativeDelay, got: %v", err)
	}
}

