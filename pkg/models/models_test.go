func TestTC_MOD_06_SpecialCharsAndQuotes(t *testing.T) {
	args := []string{"--title=\"My App\"", "file with spaces.txt", "\\path\\to\\dir"}
	item := LaunchItem{
		Path:      "/bin/echo",
		Arguments: args,
	}
	if err := item.Validate(); err != nil {
		t.Fatalf("Validation error on special args: %v", err)
	}

	data, err := json.Marshal(item)
	if err != nil {
		t.Fatalf("Marshal failed: %v", err)
	}

	var restored LaunchItem
	if err := json.Unmarshal(data, &restored); err != nil {
		t.Fatalf("Unmarshal failed: %v", err)
	}

	for i, arg := range args {
		if restored.Arguments[i] != arg {
			t.Errorf("Arg %d mismatch: expected %s, got %s", i, arg, restored.Arguments[i])
		}
	}
}

func TestTC_MOD_07_UUIDAutoGenerated(t *testing.T) {
	item := LaunchItem{
		Path: "/bin/sh",
	}
	if item.ID != "" {
		t.Fatalf("Expected initially empty ID")
	}
	if err := item.Validate(); err != nil {
		t.Fatalf("Validate failed: %v", err)
	}
	if len(item.ID) != 36 {
		t.Errorf("Expected 36-char UUID, got '%s'", item.ID)
	}
}
